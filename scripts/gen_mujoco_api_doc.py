"""Generate docs_index/mujoco_api.md: signatures + docstrings for ~25 key MuJoCo
functions, extracted by introspection from the pinned mujoco actually installed --
never hand-typed, so it can't drift from the real API. Re-run this whenever the
pinned mujoco version changes.

This is API REFERENCE, not a worked example: no full script, no solved task. The
generate/repair prompts must learn the API from here, not copy a solution.

Usage:
  python scripts/gen_mujoco_api_doc.py
"""
from __future__ import annotations

import inspect
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import mujoco  # noqa: E402

OUT_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "docs_index", "mujoco_api.md")

# Curated for what a reach/pick_place Franka Panda script actually needs: loading a
# model, stepping it, basic kinematics/Jacobian IK, and the name->id lookups the
# contract's own outcome measurement also relies on. Not the full ~500-name surface.
KEY_NAMES = [
    "MjModel",
    "MjData",
    "mj_step",
    "mj_step1",
    "mj_step2",
    "mj_forward",
    "mj_kinematics",
    "mj_comPos",
    "mj_jac",
    "mj_jacBody",
    "mj_jacSite",
    "mj_name2id",
    "mj_id2name",
    "mj_resetData",
    "mj_resetDataKeyframe",
    "mju_mulQuat",
    "mju_negQuat",
    "mju_axisAngle2Quat",
    "mju_quat2Mat",
    "mj_applyFT",
    "mj_differentiatePos",
    "mj_getState",
    "mj_setState",
    "mj_contactForce",
    "mj_isPyramidal",
    "mjtObj",
]


def doc_for(name: str) -> str:
    obj = getattr(mujoco, name, None)
    if obj is None:
        return f"### {name}\n\n(not found in this mujoco version -- removed from KEY_NAMES or renamed upstream)\n"
    doc = inspect.getdoc(obj) or "(no docstring)"
    if inspect.isclass(obj):
        # For a class, the useful part is usually the constructor signature + class doc,
        # not the full repr of every method.
        try:
            sig = str(inspect.signature(obj))
        except (TypeError, ValueError):
            sig = ""
        header = f"class {name}{sig}" if sig else f"class {name}"
        return f"### {name}\n\n```\n{header}\n```\n{doc}\n"
    return f"### {name}\n\n```\n{doc.splitlines()[0] if doc else name}\n```\n" + "\n".join(doc.splitlines()[1:]).strip() + "\n"


def main() -> int:
    parts = [
        f"# MuJoCo API reference (pinned: mujoco {mujoco.__version__})\n",
        "Generated by scripts/gen_mujoco_api_doc.py via introspection -- signatures and\n"
        "docstrings only, extracted from the actually-installed module, not hand-typed.\n"
        "Reference material, not a worked solution.\n\n"
        "Covers the calls needed to drive a Franka Panda arm and gripper through a reach "
        "or pick_place task in MuJoCo: loading a model (MjModel, MjData), stepping the "
        "simulation forward in time (mj_step), forward kinematics (mj_forward, "
        "mj_kinematics, mj_comPos), Jacobians for IK on the arm (mj_jac, mj_jacBody, "
        "mj_jacSite), looking up a body/joint/site by name (mj_name2id, mj_id2name), "
        "and resetting the arm/gripper/cube state (mj_resetData, mj_resetDataKeyframe).\n",
    ]
    for name in KEY_NAMES:
        parts.append(doc_for(name))
    content = "\n".join(parts)
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"wrote {OUT_PATH} ({len(KEY_NAMES)} entries, {len(content)} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
